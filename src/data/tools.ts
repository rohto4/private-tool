// ツール検索用のヘルパー
export function getToolBySlug(slug: string): Tool | undefined {
  return tools.find(t => t.slug === slug);
}

export function getToolsByCategory(category: 'free' | 'paid' | 'both' | 'openSource'): Tool[] {
  switch (category) {
    case 'free':
      return tools.filter(t => t.pricingModel === 'free');
    case 'paid':
      return tools.filter(t => t.pricingModel === 'paid');
    case 'both':
      return tools.filter(t => t.pricingModel === 'both');
    case 'openSource':
      return tools.filter(t => t.isOpenSource);
    default:
      return tools;
  }
}
